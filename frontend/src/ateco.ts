const SECTION_RANGES: Record<string, [number, number]> = {
  A: [1, 3], B: [5, 9], C: [10, 33], D: [35, 35], E: [36, 39], F: [41, 43], G: [45, 47],
  H: [49, 53], I: [55, 56], J: [58, 63], K: [64, 66], L: [68, 68], M: [69, 75], N: [77, 82],
  O: [84, 84], P: [85, 85], Q: [86, 88], R: [90, 93], S: [94, 96], T: [97, 98], U: [99, 99],
}

export const DIVISIONS = [
  '01', '02', '03', '05', '06', '07', '08', '09',
  ...Array.from({ length: 24 }, (_, i) => String(10 + i)),
  '35', '36', '37', '38', '39', '41', '42', '43', '45', '46', '47', '49', '50', '51', '52', '53', '55', '56',
  '58', '59', '60', '61', '62', '63', '64', '65', '66', '68', '69', '70', '71', '72', '73', '74', '75',
  '77', '78', '79', '80', '81', '82', '84', '85', '86', '87', '88', '90', '91', '92', '93', '94', '95', '96',
  '97', '98', '99',
]

export function divisionsFor(section: string): string[] {
  const range = SECTION_RANGES[section]
  if (!range) return []
  return DIVISIONS.filter((code) => Number(code) >= range[0] && Number(code) <= range[1])
}
